"""
Combined TU builder for aiuaimod.cpp.
Creates a compilation unit with shared class definitions and all function implementations.
"""
import csv, re, glob, subprocess, sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SCRATCH_DIR = REPO_ROOT / "src" / "scratch"
MATCHING_DIR = REPO_ROOT / "src" / "matching"
ACCEPTED_DIR = REPO_ROOT / "src" / "accepted_drift"
VERIFIED_LOGIC_DIR = REPO_ROOT / "src" / "verified_logic"
TOOLS_DIR = REPO_ROOT / "tools"
CONFIG_DIR = REPO_ROOT / "config" / "flags"

sys.path.insert(0, str(TOOLS_DIR))
from common import load_toolchain, repo_path, tool_env, ensure_build_subdir


HEADER = '''// Combined aiuaimod.cpp translation unit
// Generated by build_combined_tu.py
// Compiles all aiuaimod functions together for correct VC5 codegen
// (EH frames, natural register allocation)

#include "../../include/unit_ai_module.h"

// External function declarations used by aiuaimod functions
extern "C" void* __cdecl operator_new(unsigned int size);
extern "C" void __cdecl operator_delete(void* p);
extern "C" void __cdecl rge_write(int fd, void* buf, int size);
extern "C" void __cdecl rge_read(int fd, void* buf, int size);
extern "C" void* __cdecl rge_malloc(unsigned int size);

class RGE_Game_World {
public:
    void* object(int id);
};

class RGE_Static_Object {
public:
    char gap_00[0x08];
    void* master_obj;  // +0x08
    char gap_0C[0x04];
    int owner;         // +0x10
    char gap_14[0x24];
    float x;           // +0x38
    float y;           // +0x3C
    float z;           // +0x40
};

class RGE_Master_Static_Object {
public:
    char gap_00[0x14];
    short object_group;  // +0x14
};

'''


def get_functions_for_source(source_file):
    """Get function records for a source file."""
    with open(REPO_ROOT / "project_full_status.csv", encoding="utf-8", errors="replace") as f:
        rows = list(csv.DictReader(f))
    return [r for r in rows if r.get("pdb_source_file", "").lower() == source_file.lower()]


def find_source(va):
    """Find the existing source file for a function, if any."""
    for d in [SCRATCH_DIR, MATCHING_DIR, ACCEPTED_DIR, VERIFIED_LOGIC_DIR]:
        for f in sorted(d.glob(f"{va}_*.cpp")):
            return f
    return None


def extract_function_body(content):
    """Extract the function body (not the class definition) from a scratch file."""
    lines = content.split("\n")
    body_lines = []
    in_func = True
    for line in lines:
        # Skip class definitions (entirely)
        if re.match(r'^\s*(class\s+\w+|struct\s+\w+)\s*\{', line):
            in_func = False
        if not in_func and line.strip() == '};':
            in_func = True
            continue
        if not in_func:
            continue
        body_lines.append(line)
    return "\n".join(body_lines)


def build_combined_tu(source_file, output_path):
    """Build the combined TU."""
    functions = get_functions_for_source(source_file)
    
    lines = [HEADER]
    lines.append(f"// {len(functions)} functions from {source_file}")
    lines.append("")
    
    for r in sorted(functions, key=lambda x: int(x["size_bytes"])):
        va = r["va"]
        name = r["name"]
        size = r["size_bytes"]
        bucket = r.get("source_bucket", "unclaimed")
        
        src_path = find_source(va)
        if src_path:
            content = src_path.read_text()
            # Extract just the function implementation
            # Remove class definitions, includes, and everything before/after the function
            body = content
            
            # Remove #include lines
            body = re.sub(r'#include.*', '', body)
            
            # Keep only the part after the last '};' (which closes the class)
            # Actually, some files have inline class definitions. Strip them.
            # Simpler approach: if file has class definition, remove the class part
            if 'class ' in body and '};' in body:
                # Find all class definitions and remove them
                body = re.sub(r'(class\s+\w+\s*\{[^}]*\})', '', body, flags=re.DOTALL)
                # Also remove struct definitions
                body = re.sub(r'(struct\s+\w+\s*\{[^}]*\})', '', body, flags=re.DOTALL)
            
            lines.append(f"\n// --- {va} {name} ({size}B, {bucket}) ---")
            lines.append(body.strip())
        else:
            lines.append(f"\n// --- {va} {name} ({size}B) - NO SOURCE ---")
            # Create a stub from the original asm
            p = REPO_ROOT / "inventory" / "functions" / va[:4]
            matches = list(p.glob(f"{va}_*.txt"))
            if matches:
                content = matches[0].read_text()
                asm_m = re.search(r'=== OriginalAsm ===(.*?)(?:===|\$)', content, re.DOTALL)
                if asm_m:
                    lines.append(f"// Original asm:\n// " + asm_m.group(1).strip().replace("\n", "\n// "))
    
    output_path.write_text("\n".join(lines), encoding="utf-8")
    return len(functions)


def compile_combined(source_path):
    """Compile the combined TU."""
    toolchain = load_toolchain()
    cl_path = repo_path(toolchain["compiler"]["cl"])
    env = tool_env(toolchain)
    obj_path = ensure_build_subdir("obj") / source_path.name.replace(".cpp", ".obj")
    
    with open(CONFIG_DIR / "default.rsp") as f:
        flags = [l.strip() for l in f.read().split() if l.strip()]
    
    result = subprocess.run(
        [str(cl_path)] + flags + [f"/Fo{obj_path}", f"/Fa{obj_path.with_suffix('.cod')}", str(source_path)],
        capture_output=True, text=True, env=env
    )
    return result.returncode == 0, result.stdout + result.stderr


def main():
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("--source-file", default="aiuaimod.cpp")
    parser.add_argument("--compile", action="store_true")
    args = parser.parse_args()
    
    output = SCRATCH_DIR / f"combined_{args.source_file.replace('.cpp','')}.cpp"
    
    count = build_combined_tu(args.source_file, output)
    print(f"Built combined TU: {count} functions -> {output}")
    
    if args.compile:
        print("Compiling...")
        ok, msg = compile_combined(output)
        if ok:
            print("Compilation SUCCEEDED")
        else:
            print("Compilation FAILED:")
            for line in msg.split("\n")[-30:]:
                print(f"  {line}")


if __name__ == "__main__":
    main()
